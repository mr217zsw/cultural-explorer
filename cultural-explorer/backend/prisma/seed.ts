async function main() {
  for (const [name, nameEn, shortName, capital, area, population, description, geography, history, culture, landmarks, question, options, correctAnswer] of regions) {
    await prisma.region.upsert({
      where: { name },
      update: {},
      create: {
        name, nameEn, shortName, capital, area, population,
        description, geography, history, culture,
        sortOrder: regions.findIndex((item) => item[0] === name) + 1,
        landmarks: {
          create: landmarks.map((landmark, index) => ({
            name: landmark,
            description: `${landmark}是${name}具有代表性的文化或自然地标。`,
            sortOrder: index,
          })),
        },
        questions: {
          create: [
            { question, options: [...options], correctAnswer, category: 'culture', explanation: `正确答案是“${options[correctAnswer]}”。`, sortOrder: 1 },
            { question: `${name}的简称是？`, options: [shortName, '豫', '鄂', '湘'], correctAnswer: 0, category: 'geography', explanation: `${name}简称“${shortName}”。`, sortOrder: 2 },
          ],
        },
      },
    });
  }
  console.log(`Seeded ${regions.length} regions.`);
}

main().finally(() => prisma.$disconnect());
